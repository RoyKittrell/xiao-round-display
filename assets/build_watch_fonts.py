"""Bake compact, antialiased font atlases. Requires Pillow and Liberation fonts.

No font file is loaded on the microcontroller. Pass --font-root on another host.
The 4-bit glyph data and metrics are used unchanged by firmware and previews.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--font-root', type=Path, required=True)
args = parser.parse_args()
specs = [('Title', 'LiberationSerif-Regular.ttf', 22, ''.join(chr(i) for i in range(32, 127))),
         ('Small', 'LiberationSans-Regular.ttf', 11, ''.join(chr(i) for i in range(32, 127))),
         ('Rail', 'LiberationSerif-Bold.ttf', 25, '0123456789'),
         ('Modern', 'LiberationSans-Regular.ttf', 24, '0123456789')]
out = ['#pragma once', '// Generated by assets/build_watch_fonts.py; Liberation fonts, see LICENSE.txt.',
       '#include <stdint.h>', 'namespace ClockFonts {',
       'struct Glyph { uint16_t offset; uint8_t width,height,advance; int8_t left,top; };',
       'struct Font { const uint8_t* pixels; const Glyph* glyphs; uint8_t first,last; };']
for name, filename, size, chars in specs:
    font = ImageFont.truetype(str(args.font_root / filename), size * 4)
    data, glyphs = [], []
    for char in chars:
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        left, top = left // 4, top // 4
        width, height = max(1, (right + 3) // 4 - left), max(1, (bottom + 3) // 4 - top)
        im = Image.new('L', (width * 4, height * 4))
        ImageDraw.Draw(im).text((-left * 4, -top * 4), char, font=font, fill=255, anchor='ls')
        im = im.resize((width, height), Image.Resampling.LANCZOS)
        values = [min(15, (v + 8) // 17) for v in im.get_flattened_data()]
        glyphs.append((len(data), width, height, round(font.getlength(char) / 4), left, top))
        if len(values) % 2: values.append(0)
        data.extend((values[i] << 4) | values[i + 1] for i in range(0, len(values), 2))
    assert len(data) < 65536
    out += [f'const uint8_t {name}Pixels[] = {{']
    out += [','.join(f'0x{v:02x}' for v in data[i:i+24]) + ',' for i in range(0, len(data), 24)]
    out += ['};', f'const Glyph {name}Glyphs[] = {{']
    out += ['{' + ','.join(map(str, g)) + '},' for g in glyphs]
    out += ['};', f'const Font {name} = {{{name}Pixels,{name}Glyphs,{ord(chars[0])},{ord(chars[-1])}}};']
    print(name, len(data), 'bytes')
out += ['} // namespace ClockFonts']
(ROOT / 'XiaoPlayground/assets/fonts/ClockFonts.h').write_text('\n'.join(out) + '\n')
